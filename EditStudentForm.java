    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

    String name = txtName.getText().trim();
    String ageText = txtAge.getText().trim();
    String gender = cmbGender.getSelectedItem().toString();
    String course = cmbStrand.getSelectedItem().toString();
    String gradeLevel = cmbGrade.getSelectedItem().toString();
    String semester = cmbQuarter.getSelectedItem().toString();
    String schoolYear = cmbSchoolYear.getSelectedItem().toString();
    String contact = txtContact.getText().trim();
    String email = txtEmail.getText().trim();

    if (name.isEmpty()
            || ageText.isEmpty()
            || contact.isEmpty()
            || email.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Please complete all required fields."
        );

        return;
    }

    int age;

    try {

        age = Integer.parseInt(ageText);

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Age must be a number."
        );

        return;
    }

    String sql =
            "UPDATE students SET "
            + "name = ?, "
            + "age = ?, "
            + "gender = ?, "
            + "course = ?, "
            + "year_level = ?, "
            + "semester = ?, "
            + "school_year = ?, "
            + "contact_number = ?, "
            + "email = ? "
            + "WHERE student_id = ?";

    try (
        Connection con = DatabaseConnection.getConnection();
        PreparedStatement pst = con.prepareStatement(sql)
    ) {

        pst.setString(1, name);
        pst.setInt(2, age);
        pst.setString(3, gender);
        pst.setString(4, course);
        pst.setString(5, gradeLevel);
        pst.setString(6, semester);
        pst.setString(7, schoolYear);
        pst.setString(8, contact);
        pst.setString(9, email);
        pst.setString(10, studentId);

        int updated = pst.executeUpdate();

        if (updated > 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "Student information updated successfully."
            );

            // IF EDIT WAS OPENED FROM STUDENT/SUBJECT FORM
            if (subjectForm != null) {

                subjectForm.updateStudentInfo(
                        name,
                        course,
                        schoolYear,
                        gradeLevel,
                        semester
                );

                subjectForm.setVisible(true);
            }

            // IF EDIT WAS OPENED FROM ADMIN FORM
            else if (adminForm != null) {

                adminForm.refreshStudents();

                adminForm.setVisible(true);
            }

            this.dispose();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Student record was not found."
            );
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Database Error:\n"
                + e.getMessage()
        );

        e.printStackTrace();
    }



    }//GEN-LAST:event_btnSaveActionPerformed

