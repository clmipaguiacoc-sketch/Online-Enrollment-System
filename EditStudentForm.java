    private void loadStudentData() {

    String sql = "SELECT name, age, gender, course, year_level, "
            + "semester, school_year, contact_number, email, birthdate "
            + "FROM students WHERE student_id = ?";

    try {
        Connection con = DatabaseConnection.getConnection();
        PreparedStatement pst = con.prepareStatement(sql);

        pst.setString(1, studentId);

        java.sql.ResultSet rs = pst.executeQuery();

        if (rs.next()) {

            // TEXT FIELDS
            txtName.setText(rs.getString("name"));
            txtAge.setText(String.valueOf(rs.getInt("age")));
            txtContact.setText(rs.getString("contact_number"));
            txtEmail.setText(rs.getString("email"));

            // BIRTHDAY
            txtBirthday.setText(rs.getString("birthdate"));

            // GENDER
            cmbGender.removeAllItems();
            cmbGender.addItem("Select Gender");
            cmbGender.addItem("Male");
            cmbGender.addItem("Female");
            cmbGender.setSelectedItem(rs.getString("gender"));

            // STRAND
            cmbStrand.removeAllItems();
            cmbStrand.addItem("Select Strand");
            cmbStrand.addItem("Not Applicable");
            cmbStrand.addItem("TVL Plumbing");
            cmbStrand.addItem("TVL Housekeeping");
            cmbStrand.addItem("HUMSS");
            cmbStrand.addItem("STEM");
            cmbStrand.setSelectedItem(rs.getString("course"));

            // GRADE LEVEL
            cmbGrade.removeAllItems();
            cmbGrade.addItem("Grade 7");
            cmbGrade.addItem("Grade 8");
            cmbGrade.addItem("Grade 9");
            cmbGrade.addItem("Grade 10");
            cmbGrade.addItem("Grade 11");
            cmbGrade.addItem("Grade 12");
            cmbGrade.setSelectedItem(rs.getString("year_level"));

          // SEMESTER
cmbQuarter.removeAllItems();

String savedGrade = rs.getString("year_level");

if (savedGrade.equals("Grade 7")
        || savedGrade.equals("Grade 8")
        || savedGrade.equals("Grade 9")
        || savedGrade.equals("Grade 10")) {

    cmbQuarter.addItem("Quarter 1");
    cmbQuarter.addItem("Quarter 2");
    cmbQuarter.addItem("Quarter 3");
    cmbQuarter.addItem("Quarter 4");

} else {

    cmbQuarter.addItem("Quarter 1");
    cmbQuarter.addItem("Quarter 2");
    cmbQuarter.addItem("Quarter 3");
    cmbQuarter.addItem("Quarter 4");
}


            // SCHOOL YEAR
            cmbSchoolYear.removeAllItems();
            cmbSchoolYear.addItem("2026-2027");
            cmbSchoolYear.addItem("2027-2028");
            cmbSchoolYear.setSelectedItem(rs.getString("school_year"));
        }

        rs.close();
        pst.close();
        con.close();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
                this,
                "Error loading student information: " + e.getMessage()
        );
    }
}
    
    
    
