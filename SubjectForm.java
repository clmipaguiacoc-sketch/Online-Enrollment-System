private void loadSubjects() {

    DefaultTableModel model =
            (DefaultTableModel) jTableSubjects.getModel();

    model.setRowCount(0);

    model.setColumnIdentifiers(new Object[]{
        "Subject ID",
        "Subject Name",
        "Schedule",
        "Adviser"
    });

    ArrayList<Subject> subjects =
            enrollmentManager.getSubjects(
                    course,
                    schoolYear,
                    gradeLevel,
                    semester
            );

    for (Subject subject : subjects) {

        String adviser =
                enrollmentManager.getAdviser(
                        subject.getSubjectId(), 
                        subject.getSubjectName(),
                        gradeLevel,
                        course,
                        schoolYear,
                        semester,
                        section
                );

        subject.setSection(section);
        subject.setAdviser(adviser);

        model.addRow(new Object[]{
            subject.getSubjectId(),
            subject.getSubjectName(),
            subject.getSchedule(),
            subject.getAdviser()
        });
    }
}
