    private void btnEnrollActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEnrollActionPerformed
       
   ArrayList<Subject> subjects =
        enrollmentManager.getSubjects(
                course,
                schoolYear,
                gradeLevel,
                semester
        );

    if (subjects.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "No subjects are available."
        );

        return;
    }

    String sql =
            "INSERT INTO enrollments "
            + "(student_id, semester, school_year, "
            + "section, subject_id, subject_name, "
            + "schedule, room, floor) "
            + "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)";

    try (
        Connection con =
                DatabaseConnection.getConnection();
        PreparedStatement pst =
                con.prepareStatement(sql)
    ) {

        for (Subject subject : subjects) {

            pst.setString(1, studentId);
            pst.setString(2, semester);
            pst.setString(3, schoolYear);
            pst.setString(4, section);
            pst.setString(5, subject.getSubjectId());
            pst.setString(6, subject.getSubjectName());
            pst.setString(7, subject.getSchedule());
            pst.setString(8, subject.getRoom());
            pst.setString(9, subject.getFloor());

            pst.addBatch();
        }

        pst.executeBatch();

        String updateSql =
                "UPDATE students "
                + "SET enrollment_status = 'PENDING' "
                + "WHERE student_id = ?";

        try (
            PreparedStatement updatePst =
                    con.prepareStatement(updateSql)
        ) {

            updatePst.setString(1, studentId);
            updatePst.executeUpdate();
        }

        JOptionPane.showMessageDialog(
                this,
                "All subjects have been enrolled successfully."
        );

        StudentPanel studentPanel =
                new StudentPanel(studentId);

        studentPanel.setLocationRelativeTo(null);
        studentPanel.setVisible(true);

        this.dispose();

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Enrollment Error:\n"
                + e.getMessage()
        );

        e.printStackTrace();
    }



    }//GEN-LAST:event_btnEnrollActionPerformed

