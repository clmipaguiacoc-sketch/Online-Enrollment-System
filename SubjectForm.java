public void updateStudentInfo(
        String name,
        String course,
        String schoolYear,
        String gradeLevel,
        String semester) {

    this.studentName = name;
    this.course = course;
    this.schoolYear = schoolYear;
    this.gradeLevel = gradeLevel;
    this.semester = semester;

    txtStudentName.setText(name);
    txtCourse.setText(course);
    txtSchoolYear.setText(schoolYear);
    txtGradeLevel.setText(gradeLevel);
    txtSemester.setText(semester);

    // Generate new section based on the edited grade level
    this.section = generateSection(
            gradeLevel,
            course,
            schoolYear
    );

    // Display the new section
    txtSection.setText(this.section);

    jTableSubjects.clearSelection();

    loadSubjects();
}
